// Content digest for vocabulary work (Phase 4): one short entry per item, no full text.
import path from 'node:path';
import { loadItems } from './entities.mjs';

const section = (content, heading) => {
  const m = content.match(new RegExp(`^## ${heading}[^\\n]*\\n([\\s\\S]*?)(?=^## (?!#)|(?![\\s\\S]))`, 'm'));
  return m ? m[1] : '';
};
const plain = (s) => s.replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim();
const firstSentence = (s) => (plain(s).match(/^.*?[.!?](?=\s|$)/)?.[0] ?? plain(s));

/** Markdown digest: title, type, description (or first Summary sentence), first 3 Key takeaways. */
export function digest(root) {
  const items = loadItems(root).sort((a, b) => a.file.localeCompare(b.file));
  const out = ['# Content digest', '', `Generated by \`kb digest\`. ${items.length} items: title, type, description and up to 3 key takeaways. No full text.`, ''];
  for (const it of items) {
    const d = it.data;
    const desc = d.description ? plain(String(d.description)) : firstSentence(section(it.content, 'Summary'));
    const takeaways = section(it.content, 'Key takeaways').split('\n')
      .filter((l) => /^\s*[-*] /.test(l)).slice(0, 3).map((l) => `- ${plain(l.replace(/^\s*[-*] /, ''))}`);
    out.push(`## ${plain(String(d.title ?? path.basename(it.file, '.md')))}`, '',
      `\`${path.basename(it.file, '.md')}\` · ${d.type ?? '?'}${desc ? ` · ${desc}` : ''}`, ...takeaways, '');
  }
  return { count: items.length, text: out.join('\n') };
}
