// Candidate duplicate entities among tools, people and organizations. Script only; never merges.
import { loadEntities, asList } from './entities.mjs';

const DIRS = ['tools', 'people', 'organizations'];
// Words that often separate a product name from its company name ("Grafana" vs "Grafana Labs").
const COMPANY_WORDS = /\b(labs?|inc|llc|ltd|gmbh|corp|corporation|company|co|hq|team|ai|io|app|dev|docs|documentation|specification|project|org|official|cli|platform)\b/g;
const GENERIC_HOSTS = new Set(['github.com', 'linkedin.com', 'youtube.com', 'medium.com', 'substack.com', 'x.com', 'twitter.com', 'npmjs.com', 'gitlab.com', 'leanpub.com', 'payhip.com']);

/** Compare form: no accents, no case, no punctuation, no spaces. */
export const normName = (s) => String(s).normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const words = (s) => String(s).normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const coreName = (s) => normName(words(s).replace(COMPANY_WORDS, ' '));

function host(u) {
  try { return new URL(u).hostname.replace(/^www\./, '').toLowerCase(); } catch { return null; }
}

function lev(a, b) {
  if (Math.abs(a.length - b.length) > 2) return 3;
  const d = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let prev = d[0]; d[0] = i;
    for (let j = 1; j <= b.length; j++) { const t = d[j]; d[j] = Math.min(d[j] + 1, d[j - 1] + 1, prev + (a[i - 1] === b[j - 1] ? 0 : 1)); prev = t; }
  }
  return d[b.length];
}

export function findDuplicates(root) {
  const ents = loadEntities(root).filter((e) => DIRS.includes(e.dir)).map((e) => {
    const names = [e.title, ...asList(e['alt-labels'])].filter(Boolean);
    const hosts = [e.resource, ...asList(e['same-as'])].map(host).filter((h) => h && !GENERIC_HOSTS.has(h));
    return { ...e, names, norms: new Set(names.map(normName)), cores: new Set(names.map(coreName).filter((c) => c.length >= 3)), hosts: new Set(hosts) };
  });
  const pairs = [];
  for (let i = 0; i < ents.length; i++) {
    for (let j = i + 1; j < ents.length; j++) {
      const a = ents[i], b = ents[j]; const why = [];
      const toolOrg = new Set([a.dir, b.dir]).size === 2 && [a.dir, b.dir].includes('tools') && [a.dir, b.dir].includes('organizations');
      if ([...a.norms].some((n) => b.norms.has(n))) why.push('same name');
      else if ([...a.cores].some((n) => b.cores.has(n))) why.push('same name apart from a company word');
      else if ([...a.norms].some((x) => x.length >= 6 && [...b.norms].some((y) => y.length >= 6 && lev(x, y) <= 1))) why.push('names differ by one character');
      const sharedHost = [...a.hosts].find((h) => b.hosts.has(h));
      if (sharedHost) why.push(`same website host (${sharedHost})`);
      if (!why.length) continue;
      const nameMatch = why.some((w) => !w.startsWith('same website host'));
      const group = toolOrg && nameMatch ? 'product' : why[0] === 'same name' ? 'likely' : nameMatch ? 'near' : 'host';
      pairs.push({ group, kind: a.dir === b.dir ? `both ${a.dir}` : `${a.dir} vs ${b.dir}`, a, b, why });
    }
  }
  const order = { likely: 0, near: 1, product: 2, host: 3 };
  return pairs.sort((x, y) => order[x.group] - order[y.group] || x.a.dir.localeCompare(y.a.dir) || x.a.slug.localeCompare(y.a.slug));
}

export function renderDuplicates(pairs, date) {
  const ref = (e) => `\`${e.dir}/${e.slug}.md\` (${e.title})`;
  const of = (...g) => pairs.filter((p) => g.includes(p.group));
  const table = (ps) => ['| A | B | Kind | Why |', '|---|---|---|---|', ...ps.map((p) => `| ${ref(p.a)} | ${ref(p.b)} | ${p.kind} | ${p.why.join('; ')} |`), ''];
  const out = ['# Candidate duplicate entities', '', `Generated by \`kb entity-duplicates\` on ${date}. Found by script: names compared ignoring case, accents and punctuation; also company words (Labs, Inc, AI, Docs, CLI…), one-character differences and shared website hosts. Nothing has been merged.`, '',
    `${pairs.length} candidate pairs.`, '',
    `## 1. Likely duplicates (${of('likely', 'near').length})`, '', `### Same normalized name (${of('likely').length})`, '', ...table(of('likely')),
    `### Near names: differ only by a company word or one character (${of('near').length})`, '', 'Weaker than a same-name match; check each.', '', ...table(of('near')),
    `## 2. Product vs company (${of('product').length})`, '', 'A tool and an organization with the same or nearly the same name. Both files may be correct (a product and the company that makes it).', '', ...table(of('product')),
    `## 3. Host-only matches: probably different (${of('host').length})`, '', 'Names do not match; the entities only share a website host (for example several products documented on one docs domain).', '', ...table(of('host'))];
  return out.join('\n');
}
