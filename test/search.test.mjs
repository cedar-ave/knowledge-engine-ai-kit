import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { buildCatalog, loadCatalog, expandQuestion, resultIds, indexPaths, missingQmdEnv, catalogMatch, fuseRRF, openRetriever } from '../lib/search.mjs';
import { renderReport, explainMisses } from '../lib/eval.mjs';

function copySamples() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'kb-search-'));
  fs.cpSync('samples', dir, { recursive: true });
  return dir;
}

test('build-catalog: one line per item, facets and segment slugs, no body or hashes', () => {
  const root = copySamples();
  const n = buildCatalog(root);
  const cat = loadCatalog(root);
  assert.equal(cat.length, n);
  const ep = cat.find((c) => c.id === 'yt:EPISODE0001');
  assert.equal(ep.file, 'items/yt-keeping-docs-honest-at-scale-96f61ed0.md');
  assert.deepEqual(ep.segments.map((s) => s.slug), ['introduction', 'the-drift-gate']);
  assert.ok(ep.concepts.includes('Content drift') && !('captured-text-sha256' in ep));
  assert.ok(!fs.readFileSync(path.join(root, 'catalog.jsonl'), 'utf8').includes('## Summary'));
});

test('qmd-env: only variables not already set, as strings', () => {
  const root = copySamples();
  fs.writeFileSync(path.join(root, 'kb.config.yaml'), 'qmd-env:\n  KB_TEST_DEVICE: 1\n  KB_TEST_SET: x\n');
  process.env.KB_TEST_SET = 'already';
  try {
    assert.deepEqual(missingQmdEnv(root), { KB_TEST_DEVICE: '1' });
  } finally {
    delete process.env.KB_TEST_SET;
  }
});

test('thesaurus expansion matches alt-labels and adds narrower terms', () => {
  const root = copySamples();
  const x = expandQuestion(root, 'How do I stop stale docs?');
  assert.ok(x.terms.includes('topics:Content drift'));
  assert.ok(x.phrases.includes('Content drift') && x.phrases.includes('docs drift'));
  const y = expandQuestion(root, 'What is content accuracy?');
  assert.ok(y.phrases.includes('Content drift'), 'narrower term of Content accuracy');
  const z = expandQuestion(root, 'Is our content drifting?');
  assert.ok(z.terms.includes('topics:Content drift'), 'stems: drifting matches drift');
});

test('result ids: qmd paths map to item ids in rank order without duplicates', () => {
  const byFile = new Map([['a-1.md', 'web:a'], ['b-2.md', 'web:b']]);
  const ids = resultIds([{ file: 'qmd://kb-items/b-2.md' }, { displayPath: 'kb-items/a-1.md' }, { file: 'qmd://kb-items/b-2.md?index=x' }, { file: 'qmd://kb-items/zz.md' }], byFile);
  assert.deepEqual(ids, ['web:b', 'web:a']);
  assert.match(indexPaths('kb-baseline').dbPath, /kb-baseline\.sqlite$/);
});

test('eval report: recall table, per-question rows, misses and recommendation', () => {
  const q = (recall, ms) => ({ recall, msMean: ms, msMedian: ms, warmupMs: 5000, questions: [{ id: 'q01', question: 'Q?', gap: false, must: 2, hits: recall * 2, recall, ms, missed: recall < 1 ? ['web:b'] : [], top: [] }] });
  const md = renderReport({ k: 10, items: 2, tagged: 1, missing: ['web:gone'], modes: { fast: q(0.5, 200), query: q(1, 20000) }, title: { 'web:b': 'B title' } });
  assert.match(md, /GENERATED by kb eval/);
  assert.match(md, /\| fast \| 50% \|/);
  assert.match(md, /Recommendation: \*\*query\*\*/);
  assert.match(md, /`web:b` B title/);
  assert.match(md, /`web:gone`/);
});

test('retriever: asks qmd for k * 10 results and dedupes to k items', async () => {
  const root = copySamples();
  const files = loadCatalog(root).map((c) => `qmd://kb-items/${path.posix.basename(c.file)}`);
  const calls = [];
  const store = { search: async (o) => { calls.push(o.limit); return files.flatMap((f) => [{ file: f }, { file: f }]); }, close: async () => {} };
  const r = await openRetriever(root, { store });
  const { ids } = await r.retrieve('query', 'anything', 2);
  assert.deepEqual(calls, [20]);
  assert.equal(ids.length, Math.min(2, files.length));
  assert.equal(new Set(ids).size, ids.length);
});

test('fast mode: catalog facet matches ranked by matching terms, fused with qmd by RRF', async () => {
  const cat = [
    { id: 'a', concepts: ['Content drift'] },
    { id: 'b', concepts: ['Content drift'], 'doc-types': ['api-reference-docs'] },
    { id: 'c', genre: ['opinion'], 'knowledge-types': ['how-to'], 'lifecycle-stages': ['maintain'] },
    { id: 'd', organizations: ['elastic'] },
  ];
  // genre, knowledge-types and lifecycle-stages are not matched.
  assert.deepEqual(catalogMatch(cat, ['topics:Content drift', 'doc-types:api-reference-docs', 'x:elastic', 'genre:opinion', 'knowledge-types:how-to', 'lifecycle-stages:maintain']), ['b', 'a', 'd']);
  assert.deepEqual(catalogMatch(cat, []), []);
  // A term shared by maxShare items is skipped; the list is cut to top.
  assert.deepEqual(catalogMatch(cat, ['topics:Content drift', 'x:elastic'], { maxShare: 2 }), ['d']);
  assert.deepEqual(catalogMatch(cat, ['topics:Content drift', 'doc-types:api-reference-docs'], { top: 1 }), ['b']);
  const many = Array.from({ length: 30 }, (_, i) => ({ id: `m${i}`, concepts: ['Common'] }));
  assert.deepEqual(catalogMatch([...many, ...cat], ['c:Common', 'c:Content drift']), ['a', 'b']);
  assert.equal(catalogMatch(many.slice(0, 29), ['c:Common']).length, 20);
  // b is second in both lists, so it beats a and c, which each top only one.
  assert.deepEqual(fuseRRF([['a', 'b'], ['c', 'b']]), ['b', 'a', 'c']);
  // A half-weight list loses ties to the full-weight one.
  assert.deepEqual(fuseRRF([['a'], ['c']], 60, [1, 0.5]), ['a', 'c']);

  const root = copySamples();
  const store = { search: async () => [], close: async () => {} };
  const r = await openRetriever(root, { store });
  const { ids } = await r.retrieve('fast', 'How do I stop stale docs?', 3);
  const drift = loadCatalog(root).filter((c) => c.concepts?.includes('Content drift')).map((c) => c.id);
  assert.deepEqual(ids, drift.slice(0, 3), 'catalog matches on Content drift with no qmd hits');
  process.env.KB_NO_CATALOG = '1';
  try {
    assert.deepEqual((await r.retrieve('fast', 'How do I stop stale docs?', 3)).ids, [], 'KB_NO_CATALOG=1 turns the catalog off');
  } finally { delete process.env.KB_NO_CATALOG; }
});

test('eval --explain: matched terms, facets of missed items and ranks in the qmd and catalog lists', () => {
  const catalog = [{ id: 'a', concepts: ['Content drift'], 'doc-types': ['api-reference-docs'] }, { id: 'b' }];
  const e = explainMisses({ terms: ['topics:Content drift'], qmd: ['x', 'b'], catalog: ['a'] }, ['a', 'b'], catalog);
  assert.deepEqual(e.terms, ['topics:Content drift']);
  assert.deepEqual(e.items[0], { id: 'a', concepts: ['Content drift'], 'example-of': [], 'doc-types': ['api-reference-docs'], qmdRank: null, catalogRank: 1 });
  assert.equal(e.items[1].qmdRank, 2);
  const q = { id: 'q01', question: 'Q?', gap: false, must: 2, hits: 0, recall: 0, ms: 1, missed: ['a', 'b'], top: [], explain: { ...e, qmdSize: 2, catalogSize: 1 } };
  const md = renderReport({ k: 10, items: 2, tagged: 0, missing: [], modes: { fast: { recall: 0, msMean: 1, msMedian: 1, warmupMs: 1, questions: [q] } }, title: { a: 'A title' } });
  assert.match(md, /## Explain: fast questions scoring 0/);
  assert.match(md, /Matched terms: topics:Content drift/);
  assert.match(md, /concepts: Content drift; example-of: —; doc-types: api-reference-docs/);
  assert.match(md, /qmd rank: not in 2; catalog rank: 1 of 1/);
  assert.match(md, /qmd rank: 2 of 2; catalog rank: not in 1/);
});

test('fast mode returns explain data; query mode does not', async () => {
  const root = copySamples();
  const store = { search: async () => [], close: async () => {} };
  const r = await openRetriever(root, { store });
  const f = await r.retrieve('fast', 'How do I stop stale docs?', 3);
  assert.ok(f.explain.terms.includes('topics:Content drift'));
  assert.deepEqual(f.explain.qmd, []);
  assert.ok(f.explain.catalog.length >= f.ids.length);
  assert.equal((await r.retrieve('query', 'anything', 3)).explain, undefined);
});
