import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { buildCatalog, loadCatalog, expandQuestion, resultIds, indexPaths } from '../lib/search.mjs';
import { renderReport } from '../lib/eval.mjs';

function copySamples() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'kb-search-'));
  fs.cpSync('samples', dir, { recursive: true });
  return dir;
}

test('build-catalog: one line per item, facets and segment slugs, no body or hashes', () => {
  const root = copySamples();
  const n = buildCatalog(root);
  const cat = loadCatalog(root);
  assert.equal(cat.length, n);
  const ep = cat.find((c) => c.id === 'yt:EPISODE0001');
  assert.equal(ep.file, 'items/yt-keeping-docs-honest-at-scale-96f61ed0.md');
  assert.deepEqual(ep.segments.map((s) => s.slug), ['introduction', 'the-drift-gate']);
  assert.ok(ep.concepts.includes('Content drift') && !('captured-text-sha256' in ep));
  assert.ok(!fs.readFileSync(path.join(root, 'catalog.jsonl'), 'utf8').includes('## Summary'));
});

test('thesaurus expansion matches alt-labels and adds narrower terms', () => {
  const root = copySamples();
  const x = expandQuestion(root, 'How do I stop stale docs?');
  assert.ok(x.terms.includes('topics:Content drift'));
  assert.ok(x.phrases.includes('Content drift') && x.phrases.includes('docs drift'));
  const y = expandQuestion(root, 'What is content accuracy?');
  assert.ok(y.phrases.includes('Content drift'), 'narrower term of Content accuracy');
});

test('result ids: qmd paths map to item ids in rank order without duplicates', () => {
  const byFile = new Map([['a-1.md', 'web:a'], ['b-2.md', 'web:b']]);
  const ids = resultIds([{ file: 'qmd://kb-items/b-2.md' }, { displayPath: 'kb-items/a-1.md' }, { file: 'qmd://kb-items/b-2.md?index=x' }, { file: 'qmd://kb-items/zz.md' }], byFile);
  assert.deepEqual(ids, ['web:b', 'web:a']);
  assert.match(indexPaths('kb-baseline').dbPath, /kb-baseline\.sqlite$/);
});

test('eval report: recall table, per-question rows, misses and recommendation', () => {
  const q = (recall, ms) => ({ recall, msMean: ms, msMedian: ms, warmupMs: 5000, questions: [{ id: 'q01', question: 'Q?', gap: false, must: 2, hits: recall * 2, recall, ms, missed: recall < 1 ? ['web:b'] : [], top: [] }] });
  const md = renderReport({ k: 10, items: 2, tagged: 1, missing: ['web:gone'], modes: { fast: q(0.5, 200), query: q(1, 20000) }, title: { 'web:b': 'B title' } });
  assert.match(md, /GENERATED by kb eval/);
  assert.match(md, /\| fast \| 50% \|/);
  assert.match(md, /Recommendation: \*\*query\*\*/);
  assert.match(md, /`web:b` B title/);
  assert.match(md, /`web:gone`/);
});
